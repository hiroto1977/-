/**
 * **断りの文は、複数の欄を「・」でつなぐ。** (パス 502)
 *
 * `saveRefusalNote` (保存を断る文) の区切り `'・'` を `""` にする変異体が生き残っていた。
 * 既存の `guardOutcome.test.ts` は保存の断りを**欄が 1 つの標本**でしか見ておらず
 * (判定の断り `refusalNote` だけが 2 欄の標本を持つ)、区切りが消えても通っていた。
 * 区切りが消えると「床面積 (m²)段数を直すまで…」のように欄の名前が 1 語に繋がり、
 * **どの欄を直せば保存できるか**が読めなくなる。
 *
 * 2 つの断りは同じ区切りを使う (別の綴りにならない) ので、両方を同じ表で留める。
 */
import { describe, expect, it } from 'vitest';
import { refusalNote, saveRefusalNote } from '../inputGuards';

describe('断りの文 — 複数の欄の区切り (パス 502)', () => {
  it('★ 保存の断り: 2 欄・3 欄を「・」で並べる (文は 1 つに繋がり、欄の数だけ区切りが入る)', () => {
    expect(saveRefusalNote(['床面積 (m²)', '段数'])).toBe(
      '床面積 (m²)・段数を直すまで、保存していません（欄の下の指摘どおりに直すと保存できます）。',
    );
    expect(saveRefusalNote(['甲', '乙', '丙'])).toBe(
      '甲・乙・丙を直すまで、保存していません（欄の下の指摘どおりに直すと保存できます）。',
    );
  });

  it('★ 判定の断りも同じ区切り: 3 欄を「・」で並べる', () => {
    expect(refusalNote(['甲', '乙', '丙'])).toBe(
      '甲・乙・丙を直すまで、この判定は算定していません（欄の下の指摘どおりに直すと判定が出ます）。',
    );
  });

  it('★ 対照: 欄が 1 つなら区切りは入らず、0 欄なら断りそのものを出さない (null)', () => {
    expect(saveRefusalNote(['甲'])).toBe('甲を直すまで、保存していません（欄の下の指摘どおりに直すと保存できます）。');
    expect(saveRefusalNote([])).toBeNull();
    expect(refusalNote([])).toBeNull();
  });
});
