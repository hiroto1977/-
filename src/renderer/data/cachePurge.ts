/**
 * **キャッシュパージの確認文と、URL 一覧の読み取り。** (2026-09-12 · パス 154)
 *
 * ## なぜ要るか
 *
 * Cloudflare の画面には「ゾーン全体（破壊的）」という選択肢が在り、
 * **画面自身がその操作を破壊的だと名乗っている**。それなのに 2026-09-12 まで
 * 「パージ実行」は 1 回押すだけで `purgeEverything: true` を送っていた ——
 * 確認は 1 つも無い。
 *
 * このリポジトリの標準は逆である。`window.confirm` は**もっと軽い操作**にも付いている:
 *
 * | 操作 | 確認 |
 * |---|---|
 * | ライブラリの 1 ファイル削除 | 「このファイルを削除しますか?」 |
 * | ライブラリ全削除 | 「元に戻せません」 |
 * | 資格情報 1 件の削除 | 「… を削除しますか?」 |
 * | プロキシ設定の削除 / フォルダ連携の解除 | 有り |
 * | 形式の合わないレコードの削除 | 件数つき |
 * | 上書き値を既定に戻す | 件数つき |
 * | バックアップの置換復元 | 消える件数つき (パス 129) |
 * | 平文バックアップ | さらす物の件数つき (パス 130) |
 * | すべてのデータを削除 | 文字列の入力を要求 (パス 136) |
 * | **ゾーン全体のキャッシュパージ** | **無し** ← ここ |
 *
 * しかもこれは**端末の外**に効く唯一の破壊的操作である。押した瞬間に稼働中の CDN の
 * キャッシュが全部消え、取り消せず、配信元へ負荷が戻る。局所的なファイル削除に
 * 確認を付けて、これに付けないのは順序が逆だった。
 *
 * ## 文面の作り
 *
 * **範囲を名前で言う。** 画面が持っているのはゾーンの id (`023e105f4…`) だが、
 * 確認文に id を出しても読む人は何を消すのか判らない —— 選択肢に出ている
 * ゾーン名で言う (パス 101 の教訓: 断りがラベルを写すとずれる。実物を読む)。
 */

/** URL 指定パージの入力欄を、送る一覧に読み替える。空行は落とす。 */
export function purgeUrlList(text: string): readonly string[] {
  return text
    .split(/\r?\n/)
    .map((s) => s.trim())
    .filter((s) => s.length > 0);
}

/**
 * ゾーン全体パージの確認文。**範囲・取り消せないこと・配信元への影響**を言う。
 *
 * `zoneName` が空 (選択肢に無い id が入っている等) のときは、名前を騙らずに
 * 「選択したゾーン」と言う —— 空文字を埋め込むと「 のキャッシュ」という
 * 意味を持たない文になる。
 */
export function purgeEverythingConfirmMessage(zoneName: string): string {
  const target = zoneName.trim().length === 0 ? '選択したゾーン' : zoneName.trim();
  return [
    `${target} のキャッシュを全て削除します。`,
    'キャッシュ済みのすべてのファイルが対象で、元に戻せません。',
    '次のアクセスから配信元 (オリジン) へ直接リクエストが向かうため、一時的に負荷が上がります。',
    'よろしいですか？',
  ].join('\n');
}
