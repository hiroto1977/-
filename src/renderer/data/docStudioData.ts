/**
 * 書類スタジオ — 単一データソース。
 *
 * これまで個別の単体 HTML（経営書類スタジオ／電子定款メーカー／就業規則メーカー）
 * に分散していたテンプレート定義を、アプリ内サービスとして統合するための
 * 一元化モジュール。検証済みコンプライアンス知識（complianceKnowledge.ts —
 * インボイス法定6要件・2024労働条件明示改正・取適法(2026/1)・フリーランス新法・
 * 会社法・印紙税・営業秘密・個人情報保護法 等）を条文と注意書きに反映済み。
 *
 * 免責: 生成される書類は一般的テンプレートであり法的助言ではない。
 */

export interface DocField {
  readonly k: string;
  readonly label: string;
  readonly ph?: string;
  readonly def?: string;
  readonly options?: readonly string[]; // select
  readonly num?: boolean;
}

/** 書類本文のブロック。text 系は {{k}} プレースホルダを含む。 */
export interface DocBlock {
  readonly center?: string;
  readonly h?: string;
  readonly p?: string;
  readonly right?: string;
  readonly list?: readonly string[];
  readonly items?: true; // 品目1..3 明細表 (10% 単一税率・自動集計)
  readonly invoiceItems?: true; // 適格請求書明細 (税率別・端数税率ごと1回)
  readonly sign?: true; // 甲乙署名欄
  readonly bigAmount?: true; // 領収書の金額枠
  readonly stamp?: true; // 収入印紙枠
}

export interface StudioDoc {
  readonly id: string;
  readonly icon: string;
  readonly cat: string;
  readonly label: string;
  readonly fields: readonly DocField[];
  readonly body: readonly DocBlock[];
  readonly note: readonly string[];
}

