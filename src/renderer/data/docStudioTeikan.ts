/**
 * 定款（電子定款）の本文生成。
 *
 * 書式データ（docStudioData.ts）から切り出してある。定款は登記に使う法的文書で、
 * 章が 1 つ落ちても・条文が空文字になっても、見た目は「それらしい書面」のまま出てしまう。
 * データと違って分岐を持つ以上、単体テストと mutation で章立てごと固定する。
 *
 * 章・条の連番は呼び出し側（DocstudioPage）が採番する。ここは構造だけを返す。
 */

export interface TeikanArticle {
  readonly t: string;
  readonly body: readonly string[];
  readonly list?: readonly string[];
}
export interface TeikanChapter {
  readonly chapter: string;
  readonly articles: readonly TeikanArticle[];
}

type Val = (k: string) => string;

function purposes(val: Val): string[] {
  const out: string[] = [];
  for (const k of ['p1', 'p2', 'p3', 'p4', 'p5']) if (val(k)) out.push(val(k));
  return out;
}
function fyText(val: Val): string {
  const s = val('fyStart') || '4月';
  const n = Number.parseInt(s, 10);
  const endMonth = n === 1 ? 12 : n - 1;
  return `毎年${n}月1日から${n === 1 ? '同年' : '翌年'}${endMonth}月末日までの年1期とする。`;
}
function koukokuText(val: Val): string {
  // Val は必ず文字列を返す契約（呼び出し側が `values[k] ?? ''` で解決済み）。
  if (val('koukoku').includes('電子公告')) {
    return `当会社の公告は、電子公告により行う。公告掲載 URL は ${val('kohoUrl') || '【電子公告のURL】'} とする。ただし、事故その他やむを得ない事由によって電子公告による公告をすることができない場合は、官報に掲載する方法により行う。`;
  }
  return '当会社の公告は、官報に掲載する方法により行う。';
}
/**
 * 入力された発起人／社員。氏名が空の行は無いものとして詰める。
 *
 * 1 人も入力が無ければ差込の目印を 1 名分だけ返す。目印はここで解決してしまう
 * （呼び出し側で `|| '【…】'` を書くと、空文字と未設定が同じ結果になり、
 * 値が本当に渡っているのかテストで区別できなくなる）。
 */
function members(val: Val, ph: { name: string; addr: string; kabu: string }): { name: string; addr: string; kabu: string }[] {
  const out = ['f1', 'f2']
    .filter((p) => val(`${p}name`))
    .map((p) => ({ name: val(`${p}name`), addr: val(`${p}addr`), kabu: val(`${p}kabu`) }));
  return out.length > 0 ? out : [ph];
}

/** 発起人（株式会社）と社員（合同会社）で差込の目印が変わる。 */
const KK_PH = { name: '【発起人1 氏名】', addr: '【発起人1 住所】', kabu: '【引受株数・出資額】' };
const GK_PH = { name: '【社員1 氏名】', addr: '【社員1 住所】', kabu: '【出資額】' };

/** 商号は未入力なら会社種類に応じた差込の目印にする。 */
function shogoOr(val: Val, fallback: string): string {
  return val('shogo') || fallback;
}

