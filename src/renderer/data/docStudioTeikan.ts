/** 定款の締め文＋署名欄（呼び出し側でプレビュー末尾に付ける）。 */
export function teikanClosing(val: Val, type: 'kk' | 'gk'): { closing: string; signers: string[]; date: string } {
  const kk = type === 'kk';
  const role = kk ? '発起人' : '社員';
  return {
    closing: `以上、${shogoOr(val, kk ? '株式会社【商号】' : '合同会社【商号】')} の設立のため、この定款を電磁的記録により作成し、${role}が次に電子署名する。`,
    signers: members(val, kk ? KK_PH : GK_PH).map((m) => `${role}\u3000${m.name}\u3000（電子署名）`),
    date: val('date') || '【定款作成日】',
  };
}
