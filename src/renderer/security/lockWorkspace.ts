/**
 * 施錠の中身を **1 つの名前**にする。
 *
 * ## なぜ関数に出すのか (2026-08-23 実測)
 *
 * 自動施錠の値打ちは **鍵をメモリから落とすこと**で、画面を隠すことではない。
 * ところがその 2 つは `App.tsx` の `onLock` に**並べて書いてあるだけ**だった:
 *
 * ```tsx
 * onLock: () => {
 *   getVault().lock();       // ← これが本体
 *   setVaultUnlocked(false); // ← これは見た目
 * }
 * ```
 *
 * 実測で前者だけ消すと、**10,381 件の検査が全部緑のまま通り**、型検査も通った。
 * つまり「画面は施錠、鍵は生きたまま」へ退化しても誰も気づけない。そうなると
 * 施錠は演出になり、施錠後に XSS や拡張から `getToken` を呼べば資格情報は
 * 全部読める —— `webauthn.ts` の `verifyBiometric` を fail-closed に畳んだのと
 * 同じ「所持の演出」を、こちらは作ってしまう形。
 *
 * ## 関数に出すだけでは足りない
 *
 * 同じ形を直した `dbPosture.ts` は組み立てを画面の外に出したが、**画面が
 * それを呼んでいるか**は結局留められていない (あちらの注記にもそう書いてある)。
 * ここでも同じにすると、`lockWorkspace()` の行だけ消して
 * `setVaultUnlocked(false)` を残す退化がそのまま通る。
 *
 * そこで **見た目の更新をこの関数の中に取り込む**。画面はもう
 * 「鍵を落とさずに施錠状態にする」経路を、この関数を経由しては書けない ——
 * 行を消せば施錠表示ごと消えるので、**目で見て分かる壊れ方**になる。
 * (`setVaultUnlocked(false)` を別の場所へ直接書くことは依然できるが、それは
 *  「1 行消す」ではなく「名前のある関門をわざわざ迂回する」行為になる。)
 */

import { getVault } from './vault';

/**
 * 保管庫を施錠する。
 *
 * **鍵を落としてから**画面へ知らせる。順序に意味があり、`onLocked` が投げても
 * 鍵は既に落ちている —— 見た目の更新の失敗で鍵が残る方が危ない。
 *
 * @param onLocked 施錠後に画面状態を更新する処理 (省略可)。
 */
export function lockWorkspace(onLocked?: () => void): void {
  try {
    getVault().lock();
  } finally {
    onLocked?.();
  }
}
