/**
 * **`fromWareki` の 2 つの端 —— 元号名の前後の空白と、元号年 0 以下** (2026-09-30 · パス 502)。
 *
 * 全掃引 #179 の生存 2 件:
 *   - `era.trim()` —— 元号名の前後に空白が付く入力 (貼り付け・全角スペースの手前の半角) を
 *     渡す標本が無かった。`trim` を外しても答えが変わらなかった。
 *   - `eraYear < 1` —— 元号年 0 以下は「元号年は 1 以上」の契約で断る。ただし年 0 の換算は
 *     元号の始まりより前の日付になって `stamp < e.start` で落ちるので、**月を 100 以上にした
 *     入力** (呼び出し側の正規表現は 2 桁までを通すが、この関数は月・日を検めない) でしか
 *     区別できない。見張りが独立に効いていることを、その入力で留める。
 */
import { describe, expect, it } from 'vitest';
import { fromWareki } from '../bankFormat';

describe('fromWareki — 元号名の前後の空白と大文字小文字を吸収する', () => {
  it.each([
    ['前後に空白', '  令和 ', 8, 9, 30, 2026],
    ['タブと改行', '\t令和\n', 8, 9, 30, 2026],
    ['頭文字 (小文字) + 空白', ' r ', 8, 9, 30, 2026],
    ['頭文字 (大文字) + 空白', ' H ', 31, 4, 30, 2019],
    ['1 文字 + 空白', ' 昭 ', 64, 1, 7, 1989],
  ])('★ %s', (_label, era, eraYear, month, day, year) => {
    expect(fromWareki(era, eraYear, month, day)).toBe(year);
  });

  it('対照: 空白を落としても元号名でなければ null (別の語は通らない)', () => {
    expect(fromWareki('  大正 ', 8, 9, 30)).toBeNull();
  });
});

describe('fromWareki — 元号年は 1 以上', () => {
  it('★ 元号年 0 は、月が暦の外の値 (105) でも受けない', () => {
    // year = 2018、stamp = 2018*10000 + 105*100 + 1 = 20190501 (= 令和の始まり)。
    // `stamp < start` だけでは通ってしまい、見張りが無ければ 2018 を返す。
    expect(fromWareki('令和', 0, 105, 1)).toBeNull();
  });

  it('★ 元号年が負でも、月が暦の外の値 (205) で元号の始まりに届く入力を受けない', () => {
    // year = 2017、stamp = 2017*10000 + 205*100 + 1 = 20190501。
    expect(fromWareki('令和', -1, 205, 1)).toBeNull();
  });

  it('対照: 元年 (1) は受ける (令和元年 5 月 1 日 = 2019)', () => {
    expect(fromWareki('令和', 1, 5, 1)).toBe(2019);
  });
});
