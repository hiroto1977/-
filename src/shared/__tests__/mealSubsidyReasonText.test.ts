/**
 * 食事補助が非課税でない理由の**文そのもの**を、値ごと (`toEqual`) 留める (パス 502)。
 *
 * `mealSubsidyVerdict` は要件を 2 つ独立に見て、外れた要件ごとに 1 文を `reasons` へ足す。既存の検査
 * (`welfareScheme.test.ts`) は `toContain('会社負担が月')` のように**冒頭の断片**と件数しか見ないので、
 * 文の後半 —— 価額・本人負担・会社負担の**実際の額** (`（9,000 円）`) —— は、消しても緑だった。
 * 額は画面の ⛔ にそのまま出て、利用者が「どの額が要件を外れたのか」を読む唯一の場所である。
 *
 * 期待値は計算から導かず、入力の数字から**手で書いた文**にしてある。
 */
import { describe, expect, it } from 'vitest';
import { mealSubsidyVerdict } from '../welfareScheme';

describe('mealSubsidyVerdict — 外れた要件の文を額ごと留める', () => {
  it('会社負担だけが限度額を超えたら、限度額と会社負担の額を言う (要件 2 のみ)', () => {
    // 食事 20,000 円・会社負担 9,000 円 → 本人負担 11,000 円 (55%) は足りているが、9,000 > 7,500。
    expect(mealSubsidyVerdict(20_000, 9_000)).toEqual({
      taxFree: false,
      reasons: ['会社負担が月 7,500 円を超えています（9,000 円）'],
    });
  });

  it('本人負担だけが割合を下回ったら、割合と価額・本人負担の額を言う (要件 1 のみ)', () => {
    // 食事 10,000 円・会社負担 6,000 円 → 本人負担 4,000 円 (40%) < 50%。会社負担 6,000 ≤ 7,500。
    expect(mealSubsidyVerdict(10_000, 6_000)).toEqual({
      taxFree: false,
      reasons: ['本人負担が食事の価額の 50% 未満です（価額 10,000 円 / 本人負担 4,000 円）'],
    });
  });

  it('両方外れたら、要件 1 → 要件 2 の順に 2 文を並べる', () => {
    // 食事 10,000 円・会社負担 9,000 円 → 本人負担 1,000 円 (10%)・9,000 > 7,500。
    expect(mealSubsidyVerdict(10_000, 9_000).reasons).toEqual([
      '本人負担が食事の価額の 50% 未満です（価額 10,000 円 / 本人負担 1,000 円）',
      '会社負担が月 7,500 円を超えています（9,000 円）',
    ]);
  });

  it('限度額と割合を引数で差し替えたら、文の数字も差し替えた値になる (既定の 7,500 / 50% を写さない)', () => {
    // 限度額 3,500 円・割合 75%: 食事 20,000 円・会社負担 6,000 円 → 本人負担 14,000 円 < 15,000 円、6,000 > 3,500。
    expect(mealSubsidyVerdict(20_000, 6_000, 3_500, 0.75).reasons).toEqual([
      '本人負担が食事の価額の 75% 未満です（価額 20,000 円 / 本人負担 14,000 円）',
      '会社負担が月 3,500 円を超えています（6,000 円）',
    ]);
  });
});
