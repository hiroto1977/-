/**
 * 暗号パラメータ — アプリ全体で 1 つだけ持つ。
 *
 * AES-GCM の IV 長と PBKDF2 の強度は、**同じ 1 つの決定**でありながら
 * `security/vault.ts` / `security/dataCrypto.ts` / `data/cloudBackup.ts` の
 * 3 モジュールに書き写されていた。同期はコメント
 * （「vault.ts の IV_BYTES と一致させる」）だけが担保していた。
 *
 * 最も危ういのは `data/cloudBackup.ts` の鍵導出識別子で、
 * **反復回数を文字列に焼き込んでいた** (`'PBKDF2-SHA-256-600k'`)。
 * vault 側の強度を上げても、バックアップに添える暗号メタは「600k」と
 * 言い続ける — 後から復号する側が信じるのはこの文字列なので、
 * 実装とメタデータが食い違うと「復号できないバックアップ」になる。
 *
 * 実際、写経は既にずれ始めていた: ソルト長は vault が 32 バイト、
 * dataCrypto が 16 バイトで別々になっている（どちらも安全な値なので実害は
 * 無いが、「コメントで同期する」が機能していない証拠である）。
 * ソルト長は用途で分けてよい判断なので各モジュールに残し、
 * **1 つであるべきもの（IV 長・反復回数・ハッシュ）だけ**をここへ集めた。
 */

/** AES-GCM の IV 長（バイト）。GCM の標準は 96 ビット = 12 バイト。 */
export const AES_GCM_IV_BYTES = 12;

/** PBKDF2 のハッシュ。 */
export const PBKDF2_HASH = 'SHA-256' as const;

/**
 * PBKDF2 の反復回数。**新しく作る鍵**はこの値で導出する。
 *
 * 上げるときに変えるのはここだけでよい —— ただしそれが成り立つのは、
 * **保存する側が自分を作った回数を書き残している**限りにおいてである。
 * 書き残していない封緘は、この値が動いた瞬間に開けなくなる
 * (`LEGACY_KDF_ITERATIONS` の注記。パス 239 で 3 箇所直した)。
 */
export const PBKDF2_ITERATIONS = 600_000;

/**
 * 反復回数の欄が**無い**保存値を開くための回数。
 *
 * 回数を書き残す欄はあとから足された (パス 239)。それより前に書かれた
 * 保管庫のリカバリー枝・レコードの封緘は、どれも 600,000 で作られている
 * (git の履歴で確認: `security/vault.ts` は 210,000 を一度も使っていない)。
 *
 * **`PBKDF2_ITERATIONS` の別名にしてはならない。** あちらは動く定数で、
 * 上げた瞬間に古い保存値が開けなくなる —— この定数が在る理由そのものが
 * それを避けることである。だから数値リテラルで凍結し、動かさない
 * (`kdfCostProvenance.test.ts` が「リテラルであること」を原文で留めている)。
 */
export const LEGACY_KDF_ITERATIONS = 600_000;

/**
 * **新しく作る**ソルトの長さ (バイト)。用途ごとに増やすのは自由。
 *
 * 上げても既存の保存物は壊れない —— 保存済みのソルトを検査する床は
 * `MIN_STORED_SALT_BYTES` (下) で**凍結**されており、この定数とは別物である。
 * 2026-09-14 (パス 240) までは 1 つの定数が両方を兼ねていて、
 * **1 バイト上げるだけで既存のバックアップとレコード封緘が全部開かなくなった**
 * (`dataCrypto.ts` の `SALT_BYTES = MIN_SALT_BYTES` で生成側が床に張り付いていた)。
 * その危険は `deriveAesKey` の注記には書かれていたが、**上げる編集をするのは
 * この行**で、ここには「増やすのは自由」としか書いていなかった。
 */
export const MIN_SALT_BYTES = 16;

/**
 * **保存済み**のソルトを受け入れる下限 (バイト)。**凍結値。動かさない。**
 *
 * `MIN_SALT_BYTES` の別名にしてはならない —— あちらは動かしてよい定数で、
 * こちらは「既に保存されている物を開けるか」を決める。welded にすると、
 * 生成側を強くした日に**正当な過去のソルトが一斉に床を割る**
 * (バックアップは「ソルトが短すぎます」・レコード封緘は `false` =
 *  誤パスフレーズと同じ見え方・保管庫は解錠不能)。
 *
 * 16 は **これまで書き出した最小のソルト長**である (`randomSaltB64` は
 * ずっと `MIN_SALT_BYTES` = 16 で採り、`vault.ts` は独自に 32 で採ってきた)。
 *
 * **この床が止めるのは「短い」ソルトだけで、「差し替えられた」ソルトは止まらない。**
 * 保管領域へ書ける相手は 16 バイトの固定値を置けるので、事前計算の使い回しは
 * 長さの床では防げない。防ぐにはメタ自体を別の鍵で認証する必要があり、その鍵は
 * 今のところ存在しない (KCV はソルトから導出されるので自分を守れない)。
 * 床は多層防御の 1 枚であって、この攻撃の解ではない —— パス 240 で明記した。
 */
export const MIN_STORED_SALT_BYTES = 16;

/**
 * 暗号メタに載せる鍵導出の識別子。**定数から組み立てる**ので、
 * 反復回数を上げれば表示も一緒に動く。
 *
 * 1000 の倍数は `600k` の形にする — 既存のバックアップに書かれている
 * 表記がこれで、値を変えずに移行できる。
 */
export function kdfLabel(iterations: number = PBKDF2_ITERATIONS, hash: string = PBKDF2_HASH): string {
  const n = iterations % 1000 === 0 ? `${iterations / 1000}k` : String(iterations);
  return `PBKDF2-${hash}-${n}`;
}
