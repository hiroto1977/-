/**
 * **入力が天井を超えたとき、画面が述べる 1 文** (2026-09-12 · パス 168)。
 *
 * ## なぜ 1 か所に置くか
 *
 * パス 167 は業務メモの欄で「天井を超えた分を黙って落とす」を直し、超えた字数を
 * 述べる文を **`ServiceActionPanel.tsx` の JSX の中に直接**書いた。同じ形の欄は
 * 他にも在るので、そのままだと**同じ判断の文面が画面の数だけ増える** ——
 * パス 101 が直した「断りがラベルを写して実物とずれる」形である。文面をここへ寄せる。
 *
 * ## 2 つの言い分け —— 切ったのか、送らなかったのか
 *
 * どちらも「天井を超えた」だが、**利用者に起きたことが違う**ので文を分ける:
 *
 * | | いつ | 何が起きたか |
 * | --- | --- | --- |
 * | {@link clampedCeilingNote} | 保存する短い欄 (業務メモ・気分のメモ) | 天井までは入り、**超えた分は入っていない** |
 * | {@link refusedCeilingNote} | 送る欄 (AI へ渡す本文) | **何も送っていない** ——短くすれば送れる |
 *
 * 送る側を切らないのはパス 112 が決めた向き (「最新の発話は切らずに断る」)。
 * 切った本文を AI に渡すと、**途中で切れた文に対する答えが、全文に対する答えとして
 * 返ってくる** —— 分析結果は正しく見えるので、利用者には見分けられない。
 *
 * 一覧から本文を組む側 (Gmail のスレッド・Slack のチャンネル) は
 * 利用者が長さを決められないので、パス 156 が別の扱いを決めている
 * (`emotionsLimits.ts` の `packAnalyzeText` / `analyzeBatchNote` ——
 * 「先頭から入るぶんだけ送り、何件外したかを押す前に言う」)。
 * **この 3 つは別の状況に対する別の答えで、どれも「黙って落とさない」に従う。**
 */

/**
 * **「1 字」を数える単位は、文字 (コードポイント) である。** (2026-09-13 · パス 195)
 *
 * ## なぜ `value.length` ではないか
 *
 * JavaScript の `String.length` は **UTF-16 のコード単位**を数える。BMP の外の
 * 文字 —— 絵文字、JIS 2004 で入った漢字 (𠮟 U+20B9F など) —— は**1 文字で 2**
 * 数える。画面は「2000 字まで」と刷るので、そこがずれると 2 つの害が同時に出る。
 * 実測 (`'a' + '😀'.repeat(1000)` = 2001 コード単位 / **1001 文字**):
 *
 * | | 直す前 | 直した後 |
 * | --- | --- | --- |
 * | 断りの文 | 「**1 字**超えていた」 | 出ない (1001 字は 2000 字の中) |
 * | 実際の字数 | 2000 字の天井に対し **999 字下回っている** | 同じ |
 * | 欄に残る物 | 末尾が**孤立サロゲート** `0xd83d` (`isWellFormed()` が false) | 絵文字のまま |
 * | UTF-8 を往復したあと | 末尾が **`�`** に化ける (送った物と届く物が違う) | 変わらない |
 * | main の検証 | `note.length` 2000 ≤ 2000 なので**通す** | 1001 字なので通す |
 *
 * つまり「天井を超えた」と言いながら**超えていない**入力から 1 文字の半分を
 * 削り、壊れた文字列を保存側へ渡していた。**述べる数と、守る数と、切る位置は、
 * 同じ単位で数えなければならない。**
 *
 * ## 規準は既に在った
 *
 * `shared/textWrap.ts` は同じ問題をすでに解いている ——
 * 「添字で回すとサロゲートペア（絵文字など）が途中で割れる」ので `for…of` で
 * コードポイント単位に進める。折り返しだけが正しく、天井は間違っていた。
 *
 * ## 書記素クラスタではなくコードポイントにする理由
 *
 * 人が数える「1 字」に最も近いのは書記素クラスタ (👨‍👩‍👧 は 1 字・5 コードポイント)
 * だが、`Intl.Segmenter` は環境差があり、**天井は環境で変わってはいけない**
 * (同じ文が端末によって通り／通らないでは、断りの文が説明にならない)。
 * コードポイントは `for…of` だけで決まり、どの環境でも同じ数になる。
 * 結合文字を含む文は人の数え方より多く数えるが、**多く数える側は安全側**
 * (天井を越えさせない) なので、この差は害にならない。
 */
export function countChars(value: string): number {
  let n = 0;
  for (const _ch of value) n += 1; // 1 文字ずつ進む (値は使わない)
  return n;
}

/**
 * 天井までを**文字境界で**切る。
 *
 * `value.slice(0, max)` はコード単位で切るのでサロゲート対を割り、末尾に
 * 孤立サロゲートを残す (上の表)。ここは 1 文字ずつ積むので割れない。
 *
 * `max` が 0 以下なら空文字 —— 負の天井は呼び出し側の誤りだが、投げずに
 * 「1 文字も入らない」に倒す (入力中の画面を落とさない)。
 */
export function clampToCeiling(value: string, max: number): string {
  // **測れない天井は「余地なし」に倒す。** `max` が非有限だと `n >= max` が
  // 常に false になり、実測では `clampToCeiling('abcdef', NaN)` が
  // **文字列をそのまま (切らずに) 返していた** —— つまり天井が黙って外れる。
  // 天井の役目は外へ出す量を抑えることなので、読めないときに通してはいけない。
  if (!Number.isFinite(max) || max <= 0) return '';
  let out = '';
  let n = 0;
  for (const ch of value) {
    if (n >= max) break;
    out += ch;
    n += 1;
  }
  return out;
}

/**
 * **文字数が `n` 以上か。数え切らずに答える。** (2026-09-14 · パス 252)
 *
 * ## なぜ `value.length >= n` ではないか
 *
 * パス 195 は**天井**(切る側) を文字単位へ揃えたが、**床**(下限) は見ていなかった。
 * 実測 (2026-09-14): 保管庫のマスターパスワードは 9 か所で「12 文字以上」と述べ、
 * 関門 (`meetsPasswordPolicy`) は `password.length >= 12` ——
 * つまり**コード単位**を数えていた。
 *
 * | 入力 | 文字数 | コード単位 | 関門 | 画面の宣言 |
 * | --- | --- | --- | --- | --- |
 * | `'😀'.repeat(6)` | **6** | 12 | **通す** | 断るべき |
 * | `'𠮟'.repeat(6)` (JIS2004 漢字) | **6** | 12 | **通す** | 断るべき |
 * | `'😀😀😀' + 'a'.repeat(6)` | **9** | 12 | **通す** | 断るべき |
 * | `'あいうえおかきくけこさし'` | 12 | 12 | 通す | 通すべき |
 *
 * **宣言した 12 文字の床は、実文字数 6 で満たせた** —— 床の半分である。天井の側
 * (コード単位で切る) は「切り過ぎ + 孤立サロゲート」だが、床の側は
 * **緩む方向へ外れる**。同じ 1 つの単位の食い違いが、向きによって害を変える。
 *
 * ## なぜ短絡するか —— 床と天井は「安全上限」で、評価が安くなければならない
 *
 * `countChars(value) >= n` でも答えは同じだが、あちらは**文字列を最後まで**辿る。
 * 上限の判定 (`256 字以内`) は**拒むために**在るので、100 MB の入力を拒むのに
 * 100 MB 辿るのでは守りが攻撃面になる (`.length` は O(1) だからこの問題が無い)。
 * ここは `n` 文字目に届いた時点で切り上げるので O(min(n, 長さ))、
 * つまり**入力の長さに依らない**。
 */
export function atLeastChars(value: string, n: number): boolean {
  // 非有限の床は「満たせない」に倒す。`clampToCeiling` が非有限の天井を
  // 「余地なし」に倒すのと同じ向き —— 読めない規則を通してはいけない。
  if (!Number.isFinite(n)) return false;
  if (n <= 0) return true;
  let seen = 0;
  for (const _ch of value) {
    seen += 1;
    if (seen >= n) return true;
  }
  return false;
}

/**
 * **文字数が `n` を超えるか。数え切らずに答える。** (2026-09-14 · パス 252)
 *
 * 上限の側。`n + 1` 文字目に届いた時点で真を返すので O(min(n, 長さ))。
 * 理由は {@link atLeastChars} に書いた。
 */
export function moreThanChars(value: string, n: number): boolean {
  // 非有限の上限は「超えている」に倒す (読めない天井は通さない)。
  if (!Number.isFinite(n)) return true;
  if (n < 0) return true;
  let seen = 0;
  for (const _ch of value) {
    seen += 1;
    if (seen > n) return true;
  }
  return false;
}

/**
 * 天井を何字超えているか (超えていなければ 0)。
 *
 * **前後の空白を落としてから数えない** —— 画面の欄が持っている文字数をそのまま言う。
 * 空白を落とした長さで述べると、利用者が見ている字数と違う数が出る。
 *
 * 単位は {@link countChars} (文字) —— `value.length` ではない理由は上に書いた。
 */
export function charsOverCeiling(value: string, max: number): number {
  return Math.max(0, countChars(value) - max);
}

/**
 * 天井まで入れて、超えた分は落としたとき。
 *
 * 「直前の入力」と言うのは、貼り付け 1 回ごとに数え直すため ——
 * 累計で言うと、短くし直した後も古い数が残る。
 */
export function clampedCeilingNote(label: string, over: number, max: number): string {
  return (
    `${label}は ${max} 字までです。直前の入力はこれを ${over} 字超えていたため、`
    + '超えた分は入っていません（元の文章を短くしてから貼り直してください）。'
  );
}

/**
 * 天井を超えているので、まだ何も送っていないとき。
 *
 * **今の字数と超過分の両方**を言う —— 「長すぎます」だけでは、どれだけ削れば
 * 送れるのかが読めない (パス 157 で「できない指示」を直したのと同じ理由)。
 */
export function refusedCeilingNote(label: string, value: string, max: number): string {
  /*
   * **第 2 引数は文字列そのもので、数ではない。** (パス 195)
   *
   * 以前は `length: number` を取り、呼び出し側 6 か所がどれも `value.length`
   * (コード単位) を渡していた —— つまり**文面の数だけが別の単位**だった。
   * 引数を文字列にすると `.length` を渡す道が型で消える (「口はあるが
   * 繋がっていない」を作らないための、いつもの手)。
   */
  const length = countChars(value);
  const over = Math.max(0, length - max);
  return (
    `${label}は ${max} 字までです。いま ${length} 字あり、${over} 字超えています。`
    + 'この状態では送りません —— 短くしてからもう一度押してください。'
  );
}
