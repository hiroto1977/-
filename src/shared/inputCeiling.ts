/**
 * **入力が天井を超えたとき、画面が述べる 1 文** (2026-09-12 · パス 168)。
 *
 * ## なぜ 1 か所に置くか
 *
 * パス 167 は業務メモの欄で「天井を超えた分を黙って落とす」を直し、超えた字数を
 * 述べる文を **`ServiceActionPanel.tsx` の JSX の中に直接**書いた。同じ形の欄は
 * 他にも在るので、そのままだと**同じ判断の文面が画面の数だけ増える** ——
 * パス 101 が直した「断りがラベルを写して実物とずれる」形である。文面をここへ寄せる。
 *
 * ## 2 つの言い分け —— 切ったのか、送らなかったのか
 *
 * どちらも「天井を超えた」だが、**利用者に起きたことが違う**ので文を分ける:
 *
 * | | いつ | 何が起きたか |
 * | --- | --- | --- |
 * | {@link clampedCeilingNote} | 保存する短い欄 (業務メモ・気分のメモ) | 天井までは入り、**超えた分は入っていない** |
 * | {@link refusedCeilingNote} | 送る欄 (AI へ渡す本文) | **何も送っていない** ——短くすれば送れる |
 *
 * 送る側を切らないのはパス 112 が決めた向き (「最新の発話は切らずに断る」)。
 * 切った本文を AI に渡すと、**途中で切れた文に対する答えが、全文に対する答えとして
 * 返ってくる** —— 分析結果は正しく見えるので、利用者には見分けられない。
 *
 * 一覧から本文を組む側 (Gmail のスレッド・Slack のチャンネル) は
 * 利用者が長さを決められないので、パス 156 が別の扱いを決めている
 * (`emotionsLimits.ts` の `packAnalyzeText` / `analyzeBatchNote` ——
 * 「先頭から入るぶんだけ送り、何件外したかを押す前に言う」)。
 * **この 3 つは別の状況に対する別の答えで、どれも「黙って落とさない」に従う。**
 */

/**
 * 天井を何字超えているか (超えていなければ 0)。
 *
 * **前後の空白を落としてから数えない** —— 画面の欄が持っている文字数をそのまま言う。
 * 空白を落とした長さで述べると、利用者が見ている字数と違う数が出る。
 */
export function charsOverCeiling(value: string, max: number): number {
  return Math.max(0, value.length - max);
}

/**
 * 天井まで入れて、超えた分は落としたとき。
 *
 * 「直前の入力」と言うのは、貼り付け 1 回ごとに数え直すため ——
 * 累計で言うと、短くし直した後も古い数が残る。
 */
export function clampedCeilingNote(label: string, over: number, max: number): string {
  return (
    `${label}は ${max} 字までです。直前の入力はこれを ${over} 字超えていたため、`
    + '超えた分は入っていません（元の文章を短くしてから貼り直してください）。'
  );
}

/**
 * 天井を超えているので、まだ何も送っていないとき。
 *
 * **今の字数と超過分の両方**を言う —— 「長すぎます」だけでは、どれだけ削れば
 * 送れるのかが読めない (パス 157 で「できない指示」を直したのと同じ理由)。
 */
export function refusedCeilingNote(label: string, length: number, max: number): string {
  const over = Math.max(0, length - max);
  return (
    `${label}は ${max} 字までです。いま ${length} 字あり、${over} 字超えています。`
    + 'この状態では送りません —— 短くしてからもう一度押してください。'
  );
}
