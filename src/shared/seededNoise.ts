/**
 * 決定論的な擬似乱数（xorshift32）— アプリ全体で 1 つだけ持つ。
 *
 * スナップショットの模擬データに「毎回同じだが動いて見える」値を入れるために使う。
 * 真の乱数だとスクリーンショットとテストが再現しなくなるため、種から決まる値にする。
 *
 * KPI・業績・株価の 3 モジュールに同じ実装が写経されていた。乱数列そのものが
 * スナップショットの期待値を決めるので、どれか 1 つだけ式を変えると、その画面の
 * 模擬データだけが静かに別物になる。
 */

/**
 * 種から 0 以上 1 未満の値を返す。同じ種なら必ず同じ値。
 *
 * `seed | 0` で int32 に落とし、0 になったときだけ 1 を使う。0 のまま xorshift に
 * 入れると出力が 0 に貼り付いて動かなくなる（0 をいくら XOR しても 0）。
 */
export function seededNoise(seed: number): number {
  let x = (seed | 0) || 1;
  x ^= x << 13;
  x ^= x >>> 17;
  x ^= x << 5;
  return (x >>> 0) / 4294967296;
}
