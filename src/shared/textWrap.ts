/**
 * 本文を印刷幅で折り返す — アプリ全体で 1 つだけ持つ。
 *
 * main のテンプレート生成・renderer のテンプレート画面・ブラウザ版テンプレートに
 * 同じ実装が 3 つあった。折り返しは見た目に直結するので、どれか 1 つだけ直すと
 * 「同じ文書なのに経路によって改行位置が違う」ことになる。
 */

/**
 * `maxChars` 文字ごとに折り返す。段落（改行）は保持する。
 *
 * 文字の走査を `for...of` で行うのはコードポイント単位で進めるため。
 * 添字で回すとサロゲートペア（絵文字など）が途中で割れる。
 *
 * 空段落は空行として残る。段落を詰めると切れ目が消え、印刷したときに文章が
 * 地続きに見えてしまうため。空段落だけを特別扱いする分岐は要らない —
 * 走査ループが 1 度も回らず、そのまま空文字が 1 行として積まれる。
 */
export function wrapLines(text: string, maxChars: number): string[] {
  const out: string[] = [];
  for (const para of text.split(/\n/)) {
    let buf = '';
    for (const ch of para) {
      if (buf.length >= maxChars) {
        out.push(buf);
        buf = '';
      }
      buf += ch;
    }
    // 条件を付けない。非空の段落ならループ後の buf は必ず 1 文字以上あり
    // （buf を空にした直後に必ず ch を足す）、空段落なら空文字を 1 行として積む。
    // かつて 3 箇所の写経それぞれに `if (buf.length > 0)` と等価変異の pragma が
    // 貼られていたが、いずれも成り立たない条件だった。
    out.push(buf);
  }
  return out;
}
